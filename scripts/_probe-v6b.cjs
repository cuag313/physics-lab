const puppeteer=require("puppeteer-core")
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms))
;(async()=>{
 const b=await puppeteer.launch({executablePath:"C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe",headless:"new"})
 const p=await b.newPage()
 p.on("pageerror",e=>console.log("ERR",String(e).slice(0,200)))
 await p.setViewport({width:1680,height:1000,deviceScaleFactor:1})
 await p.goto("http://127.0.0.1:5199/physics-lab/",{waitUntil:"networkidle2"})
 await sleep(900)
 await p.evaluate(()=>{const e=[...document.querySelectorAll(".category-tab")].find(x=>x.innerText.includes("电学")); if(e) e.click()})
 await sleep(600)
 await p.evaluate(()=>{const d=[...document.querySelectorAll("div")].filter(x=>x.innerText.trim()==="电动机原理"); if(d.length) d[d.length-1].click()})
 await sleep(1600)
 const pt=await p.evaluate(()=>{const b=[...document.querySelectorAll(".scene-tab")].find(x=>x.innerText.includes("自己动手")); const r=b.getBoundingClientRect(); return {x:r.x+r.width/2,y:r.y+r.height/2}})
 await p.mouse.click(pt.x,pt.y); await sleep(1200)
 const st=await p.evaluate(()=>({comps:document.querySelectorAll(".esb-comp").length,hasEsmm:document.body.innerHTML.includes("esmm"),note:document.querySelector(".esb-note")?.innerText?.slice(0,60)||""}))
 console.log("after click",JSON.stringify(st))
 const mot=await p.evaluate(()=>{const l=[...document.querySelectorAll(".esb-comp")]; const e=l.find(x=>x.innerHTML.includes("esmm")); if(!e) return {n:l.length,ids:l.map(x=>x.dataset.id||x.className).slice(0,8)}; const r=e.getBoundingClientRect(); return {x:r.x,y:r.y,width:r.width,height:r.height}})
 console.log("motor",JSON.stringify(mot))
 await b.close()
})()
