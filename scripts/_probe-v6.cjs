const puppeteer=require("puppeteer-core")
const sleep=(ms)=>new Promise(r=>setTimeout(r,ms))
;(async()=>{
 const b=await puppeteer.launch({executablePath:"C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe",headless:"new"})
 const p=await b.newPage()
 const errs=[]
 p.on("pageerror",e=>errs.push(String(e).slice(0,160)))
 await p.setViewport({width:1680,height:1000,deviceScaleFactor:1})
 await p.goto("http://127.0.0.1:5199/physics-lab/",{waitUntil:"networkidle2"})
 await sleep(900)
 await p.evaluate(()=>{const e=[...document.querySelectorAll(".category-tab")].find(x=>x.innerText.includes("电学")); if(e) e.click()})
 await sleep(600)
 await p.evaluate(()=>{const d=[...document.querySelectorAll("div")].filter(x=>x.innerText.trim()==="电动机原理"); if(d.length) d[d.length-1].click()})
 await sleep(1600)
 const tabs=await p.evaluate(()=>[...document.querySelectorAll(".scene-tab")].map(x=>({t:x.innerText.trim(),r:x.getBoundingClientRect().toJSON()})))
 console.log("tabs",JSON.stringify(tabs))
 const info=await p.evaluate(()=>({hasEsmm:document.body.innerHTML.includes("esmm"),comps:document.querySelectorAll(".esb-comp").length,scene:document.querySelector(".scene-tab.active,.scene-tab[aria-selected=true]")?.innerText||"?"}))
 console.log("info",JSON.stringify(info))
 console.log("errs",errs.join(" | "))
 await b.close()
})()
